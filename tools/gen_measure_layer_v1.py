#!/usr/bin/env python3
"""Regenerate kernels/muse_decode_layer/measure_layer_v1.py (C22a', MEASUREMENT-ONLY) =
    line 1 of sonnet_v5.py + the MEASUREMENT-ONLY header + sonnet_v5.py verbatim (kernel_fn / prepare unchanged)
  + the large-M CUDA source of the MoE problem's sonnet_v4 with its route kernel patched to read local_start from the device tensor (wrap rule)
  + generate_input of problems/muse_decode_layer/reference.py inlined by tools/make_trace.py's ast inliner (names prefixed _tr_)
  + tools/measure_layer_v1_part.py (the study, wraps prepare()).
Run after any change to an input:   .venv/bin/python tools/gen_measure_layer_v1.py"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_decode_layer" / "sonnet_v5.py"
MOE = ROOT / "kernels" / "muse_moe_w4a16" / "sonnet_v4.py"
PART = ROOT / "tools" / "measure_layer_v1_part.py"
OUT = ROOT / "kernels" / "muse_decode_layer" / "measure_layer_v1.py"

MARKER = '''# MEASUREMENT-ONLY (C22a' v1, design/fable-09-out.md D4 section 2): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_layer_v1.py: do not edit.
# kernel_fn / prepare below are kernels/muse_decode_layer/sonnet_v5.py VERBATIM (board candidate C19). prepare() runs sonnet_v5's prepare(), then (untimed, <= 262 s,
# variants that do not fit are dropped, not run late) times on generate_input-recipe inputs (3 seeds, T in 1 8 16 32 128 256 = the judged loads' token counts; sliding
# layer, ctx 4096: the FFN half does not depend on it), each variant as a CUDA-graph replay after a read-only L2 flush, per-kernel start / end / stream from CUPTI:
#   front section = pooler (main stream) beside router + routing (side stream), join, pre-expert norm.   Variants:
#   ORDER   router first on the main stream, then routing on the side stream beside the pooler (stream topology only)
#   RPAR    router >= 256 CTAs, no zero-fill, no atomics: last-CTA fixup (partials summed in slice order)
#   RBIG    T >= 128: router as two cuBLAS hi/lo GEMMs (mm) or one M block (bm: W read once)
#   POOLSMEM pooler / router GEMVs with fewer pipeline stages / smaller BK so two CTAs co-reside (smem 147 KB -> 74 / 49 KB, offline ptxas)
#   TMAPOOL pooler with a host TensorDescriptor on W (cp.async.bulk.tensor; offline sm_90 compile emits 4 / 6 bulk-tensor copies): low priority
#   OSHOT   o-projection at T <= 32 as a Triton GEMV, BK 1024 (alone, against cuBLAS)
#   C24-lite Marlin+S1 against the MoE problem's large-M CUDA path at T 32 / 128 / 256 on the layer's own routing (extension compiled in a thread beside the front study)
# Output (<= 14 KB): summary first, then `K` (correctness of each variant against the baseline path), `A` (ops alone), `B layer T=<T> seed=<s> E=<distinct> | <variant>
# side_end= main_idle= pool= rout= ln=` (and the C24 `B ... c24_<path> e2e= g1= g2=` lines). See the first lines of the log for the column meanings.
'''


def moe_strings():
    spec = importlib.util.spec_from_file_location("_moe_v4", MOE)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    extra, host, cpp = m._LARGEM_EXTRA_SRC, m._LARGEM_HOST_SRC, m._LARGEM_CPP_SRC

    def patch(text, old, new):
        assert text.count(old) == 1, old
        return text.replace(old, new)

    # route kernel: local_start is a device tensor, the layer's wrap rule ((id - local_start) mod 256 < 32) instead of a Python range
    extra = patch(extra, "int* __restrict__ slotl, int n, int lo, int nloc) {", "int* __restrict__ slotl, int n, const int* __restrict__ lo_ptr, int nloc) {")
    extra = patch(extra, "    pdl_trigger();\n    for (int s = tid; s < n; s += 1024) {\n        const int gl = ids[s];\n        const int e = (gl >= lo && gl < lo + nloc) ? gl - lo : -1;",
                  "    pdl_trigger();\n    const int lo = lo_ptr[0];  // local_start: a device tensor of the layer's inputs, never read on the host\n"
                  "    for (int s = tid; s < n; s += 1024) {\n        const int gl = ids[s];\n        const int rel = (gl - lo) & 255;  // the layer's local-id rule\n"
                  "        const int e = rel < nloc ? rel : -1;")
    host = patch(host, "torch::Tensor slotl, int64_t lo, int64_t nloc) {", "torch::Tensor slotl, torch::Tensor lo, int64_t nloc) {")
    host = patch(host, "(int)ids.numel(), (int)lo, (int)nloc);", "(int)ids.numel(), lo.data_ptr<int>(), (int)nloc);")
    cpp = patch(cpp, "torch::Tensor slotl, int64_t lo, int64_t nloc);", "torch::Tensor slotl, torch::Tensor lo, int64_t nloc);")
    for t in (extra, host, cpp):
        assert "'''" not in t
    return extra, host, cpp


def build():
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_decode_layer"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    extra, host, cpp = moe_strings()
    lm = ("\n\n# ---- large-M CUDA source of kernels/muse_moe_w4a16/sonnet_v4.py, route kernel patched (local_start from the device tensor, wrap rule); generated\n"
          f"_ML_LARGEM_EXTRA_SRC = r'''{extra}'''\n_ML_LARGEM_HOST_SRC = r'''{host}'''\n_ML_LARGEM_CPP_SRC = {cpp!r}\n")
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_decode_layer", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_decode_layer/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + lm + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
