    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_decode_layer"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    gen_src, gen_name, _params = inline_generator(ROOT / "problems" / "muse_decode_layer", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_decode_layer/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + derive_kernel() + gen + "\n\n" + PART.read_text()


