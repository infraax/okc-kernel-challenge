#!/usr/bin/env python3
"""Regenerate kernels/muse_moe_w4a16/measure_grouped_v1.py = grouped_v1.py's code (USE_GROUPED off: kernel_fn is sonnet_v1's Marlin path
for every shape) + tools/measure_grouped_v1_part.py (the sweep). Run after any change to either input:
    .venv/bin/python tools/gen_measure_grouped_v1.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "kernels" / "muse_moe_w4a16" / "grouped_v1.py"
PART = ROOT / "tools" / "measure_grouped_v1_part.py"
OUT = ROOT / "kernels" / "muse_moe_w4a16" / "measure_grouped_v1.py"

HEAD = '''# okc: problem=muse_moe_w4a16
"""MEASUREMENT-ONLY candidate (design/fable-07-out.md D1 option 2, Sonnet-A). Run as `okc check`, NEVER submit.

GENERATED by tools/gen_measure_grouped_v1.py from kernels/muse_moe_w4a16/grouped_v1.py + tools/measure_grouped_v1_part.py: do not edit.
kernel_fn is sonnet_v1 (the Marlin path for every shape; scores ~1.15x). prepare() builds SGLang's Marlin state, then runs `_measure` once,
untimed, within a ~225 s budget: on synthetic skewed routing (fixed seed, nothing derived from the judge's inputs) it times the grouped
Triton GEMMs of grouped_v1 against Marlin's, each as a CUDA-graph replay after a read-only L2 flush (like the judge), at bs 32 / 128 / 256.

Phases: setup (routing, Marlin GEMM1 / GEMM2 / whole-path baselines, Marlin outputs as references) | A dequant mode probe (deq 2 / 1 / 0 on
one GEMM1 config at bs 256) | B GEMM1 sweep over {BM, BNH, CH, warps, stages} | C GEMM2 sweep | D whole large-M path (_kernel_grouped) per BM
at 1 and 2 CTAs per SM | E finals (41 reps) for the top 3 per GEMM and the other dequant modes on the best GEMM1.
Every variant is compared with Marlin's output on the same inputs (relative L2 < 2e-2 on live slots) before it is timed; wrong ones are `bad`.

Log: `MEASG` progress lines, `S moeg g<1|2> bs=<bs> <name>:<us> ...` (all screened configs, best first; F = failed to compile / launch,
B = wrong output), then `B moeg bs=<bs> | marlin g1= g2= e2e= | g1 top5 ... | g2 top5 ... | e2e <cfg>:<us> vs marlin <us> = <x>x | ok= fail= bad=`.
name = d<deq>b<BM>n<BNH>c<CH>w<warps>s<stages>[g<CTAs per SM>] (GEMM screens run 2 CTAs per SM, the whole path tries 1 and 2). Times include the graph's ~4 us fixed cost on both sides.
"""
'''


def build() -> str:
    src = SRC.read_text()
    body = src[src.index("import types\n"):]
    assert "USE_GROUPED = True" in body
    body = body.replace("USE_GROUPED = True", "USE_GROUPED = False")
    return HEAD + body.rstrip("\n") + "\n\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
