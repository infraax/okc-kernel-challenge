ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_decode_layer" / "sonnet_v5f.py"
PART = ROOT / "tools" / "measure_corridor_v1_part.py"
OUT = ROOT / "kernels" / "muse_decode_layer" / "measure_corridor_v1.py"

MARKER = '''# MEASUREMENT-ONLY (C33 v1, design/itachi-corridor.md section 7): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_corridor_v1.py: do not edit.
# kernel_fn / prepare below are kernels/muse_decode_layer/sonnet_v5f.py VERBATIM (the board kernel, 1.433x). prepare() runs v5f's prepare(), then (untimed, <= 280 s in all, variants that do
# not fit are dropped) times the WHOLE layer as one CUDA graph per variant on generate_input-recipe inputs (3 seeds; decode 1 / 16 / 32 sliding + full, verify 1 full; read-only L2 flush,
# median of 5, replay overhead subtracted), module switches flipped per variant and the graph re-captured:
#   PDL_OFF     the board (S3_PDL False)                   WAITFIRST   S3_PDL on, as built (gdc_wait first)
#   TOOLS_LIGHT S3_PDL on; each of our weight-streaming kernels prefetches its first <= 64 KB per CTA to L2 (prefetch.global.L2) BEFORE gdc_wait, then waits
#   TOOLS_FULL  the same with the CTA's whole weight slice (corridor congestion)     PRIO  critical-path stream high priority, the side stream low
#   TOOLS_LIGHT+PRIO
# Kernels with the prefetch (twins of v5f's, _mc_ prefix): _gemv_splitk (pooler, router T >= 2), _router_fix_kernel (router T = 1), _unpool_kernel, _pre_norm_kernel, _epilogue_kernel
# (gain vector) and the small-M CUDA GEMM2 (extension twin). NOT touched: cuBLAS nvjet / splitKreduce, SGLang's norm / routing kernels, Marlin (T = 32), the attention kernels (their
# K / V rows are inputs, not weights), small-M GEMM1 (its weights depend on the routing: A5). Output (<= 14 KB): `S` summary lines first (per variant and shape: layer us, x vs PDL_OFF,
# OK / DIFF against the board), the `D` decision line, `H` handover stamps (CUPTI kernel start / end inside graph replays), then `B` lines per seed.
'''

PF_HELPER = '''@triton.jit
def _mc_pf(ptrs):
    """prefetch.global.L2 of every address in `ptrs` (any shape); side effect only (is_pure=False keeps it)."""
    tl.inline_asm_elementwise("prefetch.global.L2 [$1];\\n\\tmov.u32 $0, 0;", "=r,l", [ptrs], dtype=tl.int32, is_pure=False, pack=1)
'''


def _segment(tree, text, name):
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            start = node.decorator_list[0].lineno if node.decorator_list else node.lineno
            return "\n".join(text.splitlines()[start - 1:node.end_lineno])
    raise KeyError(name)


def _sub(text, old, new, count=1):
    n = text.count(old)
    if n != count:
        raise SystemExit(f"gen_measure_corridor_v1: expected {count} x {old[:70]!r} in the board source, found {n}: sonnet_v5f.py changed, update the substitutions")
    return text.replace(old, new)


def twins():
    text = SRC.read_text()
    tree = ast.parse(text)
    out = [PF_HELPER]
    # ---- _gemv_splitk: pooler (T <= 32) and the router at T >= 2 (hi + lo weights, FP32 hidden split in registers)
    k = _segment(tree, text, "_gemv_splitk")
    k = _sub(k, "def _gemv_splitk(", "def _mc_gemv_splitk(")
    k = _sub(k, "SPLIT_X: tl.constexpr, PDL: tl.constexpr = False):", "SPLIT_X: tl.constexpr, PDL: tl.constexpr = False, PFL: tl.constexpr = 0):")
    k = _sub(k, "    if PDL:\n        tl.extra.cuda.gdc_wait()  # S3: first statement, before any load (the previous grid's outputs are this kernel's inputs)\n",
             "    if PFL > 0:   # C33: weights never depend on the previous grid: pull this CTA's first PFL lines per weight row into L2, then wait for the activations\n"
             "        _pn = tl.program_id(0)\n        _pk = tl.program_id(1)\n        _rn = _pn * BN + tl.arange(0, BN)\n        _kper = tl.cdiv(K, SPLIT * BK) * BK\n"
             "        _ko = _pk * _kper + tl.arange(0, PFL)[None, :] * 64\n        _ok = (_rn[:, None] < N) & (_ko < K) & (_ko < (_pk + 1) * _kper)\n"
             "        _off = tl.where(_ok, _rn[:, None] * stride_wn + _ko, 0)\n        _mc_pf(w_ptr + _off)\n        if HAS_LO:\n            _mc_pf(wlo_ptr + _off)\n"
             "    if PDL:\n        tl.extra.cuda.gdc_wait()\n")
    out.append(k)
    # ---- _router_fix_kernel (T = 1): hi + lo, K / SPLIT per CTA
    k = _segment(tree, text, "_router_fix_kernel")
    k = _sub(k, "def _router_fix_kernel(", "def _mc_router_fix_kernel(")
    k = _sub(k, "                       K: tl.constexpr, N: tl.constexpr):", "                       K: tl.constexpr, N: tl.constexpr, PDL: tl.constexpr = False, PFL: tl.constexpr = 0):")
    k = _sub(k, "    pid_n = tl.program_id(0)\n    pid_k = tl.program_id(1)\n    pid_m = tl.program_id(2)\n",
             "    if PFL > 0:   # C33\n        _rn = tl.program_id(0) * BN + tl.arange(0, BN)\n        _ko = tl.program_id(1) * (K // SPLIT) + tl.arange(0, PFL)[None, :] * 64\n"
             "        _mc_pf(hi_ptr + _rn[:, None] * K + _ko)\n        _mc_pf(lo_ptr + _rn[:, None] * K + _ko)\n"
             "    if PDL:\n        tl.extra.cuda.gdc_wait()\n    pid_n = tl.program_id(0)\n    pid_k = tl.program_id(1)\n    pid_m = tl.program_id(2)\n")
    k = _sub(k, "    tl.store(part_ptr + (pid_k * M + rm)[:, None] * N + rn[None, :], acc, mask=rm[:, None] < M)\n    tl.debug_barrier()\n",
             "    if PDL:\n        tl.extra.cuda.gdc_launch_dependents()\n    tl.store(part_ptr + (pid_k * M + rm)[:, None] * N + rn[None, :], acc, mask=rm[:, None] < M)\n    tl.debug_barrier()\n")
    out.append(k)
    # ---- _unpool_kernel (T <= 8)
    k = _segment(tree, text, "_unpool_kernel")
    k = _sub(k, "def _unpool_kernel(", "def _mc_unpool_kernel(")
    k = _sub(k, "K: tl.constexpr, N: tl.constexpr, NCOL: tl.constexpr, PADB: tl.constexpr):",
             "K: tl.constexpr, N: tl.constexpr, NCOL: tl.constexpr, PADB: tl.constexpr, PDL: tl.constexpr = False, PFL: tl.constexpr = 0):")
    k = _sub(k, "    pid_n = tl.program_id(0)\n    pid_k = tl.program_id(1)\n    NB: tl.constexpr = N // BN\n",
             "    if PFL > 0:   # C33 (the pad zero-fill below stays AFTER the wait: its buffer may still be read by the previous grid)\n"
             "        _rn = tl.program_id(0) * BN + tl.arange(0, BN)\n        _ko = tl.program_id(1) * (K // SPLIT) + tl.arange(0, PFL)[None, :] * 64\n"
             "        _mc_pf(w_ptr + _rn[:, None] * K + _ko)\n"
             "    if PDL:\n        tl.extra.cuda.gdc_wait()\n    pid_n = tl.program_id(0)\n    pid_k = tl.program_id(1)\n    NB: tl.constexpr = N // BN\n")
    k = _sub(k, "    optr = out_ptr + rm[:, None] * stride_o + rn[None, :]\n    if SPLIT == 1:\n",
             "    if PDL:\n        tl.extra.cuda.gdc_launch_dependents()\n    optr = out_ptr + rm[:, None] * stride_o + rn[None, :]\n    if SPLIT == 1:\n")
    out.append(k)
    # ---- _pre_norm_kernel: the gain vector
    k = _segment(tree, text, "_pre_norm_kernel")
    k = _sub(k, "def _pre_norm_kernel(", "def _mc_pre_norm_kernel(")
    k = _sub(k, "N: tl.constexpr, BLOCK: tl.constexpr):", "N: tl.constexpr, BLOCK: tl.constexpr, PDL: tl.constexpr = False, PFL: tl.constexpr = 0):")
    k = _sub(k, "    row = tl.program_id(0)\n    offs = tl.arange(0, BLOCK)\n",
             "    if PFL > 0:   # C33\n        _mc_pf(w_ptr + tl.arange(0, PFL) * 64)\n    if PDL:\n        tl.extra.cuda.gdc_wait()\n    row = tl.program_id(0)\n    offs = tl.arange(0, BLOCK)\n")
    k = _sub(k, "    inv = tl.rsqrt(tl.sum(x * x, axis=0) / N + eps)\n", "    if PDL:\n        tl.extra.cuda.gdc_launch_dependents()\n    inv = tl.rsqrt(tl.sum(x * x, axis=0) / N + eps)\n")
    out.append(k)
    # ---- _epilogue_kernel: already PDL; the gain vector before the wait
    k = _segment(tree, text, "_epilogue_kernel")
    k = _sub(k, "def _epilogue_kernel(", "def _mc_epilogue_kernel(")
    k = _sub(k, "    NPART: tl.constexpr = 1,\n):", "    NPART: tl.constexpr = 1, PFL: tl.constexpr = 0,\n):")
    k = _sub(k, "    if PDL:\n        tl.extra.cuda.gdc_wait()  # S3: y comes from the previous grid (Marlin)\n",
             "    if PFL > 0:   # C33\n        _mc_pf(w_ptr + tl.arange(0, PFL) * 64)\n    if PDL:\n        tl.extra.cuda.gdc_wait()  # S3: y comes from the previous grid (Marlin)\n")
    out.append(k)
    return "\n\n\n".join(out)


def smallm_twin():
    """(device, host, cpp) sources of the small-M extension with an L2 prefetch in GEMM2 (FUSE false) BEFORE its pdl_wait: the weight lines of the CTA's warp stream beyond the two
    register batches. Mode from a host-side static set by smallm_set_pref (0 off, 1 light = <= 16 KB per warp x 4 warps ~ 64 KB per CTA, 2 full slice): kernel_fn's calls are unchanged."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("_v5f_for_gen", SRC)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    dev, host, cpp = m._SMALLM_DEVICE_SRC, m._SMALLM_HOST_SRC, m._SMALLM_CPP_SRC
    dev = _sub(dev, "__device__ __forceinline__ u32 smem_u32(const void* p)",
               "__device__ __forceinline__ void l2_prefetch(const void* p) { asm volatile(\"prefetch.global.L2 [%0];\" :: \"l\"(p)); }\n"
               "__device__ __forceinline__ u32 smem_u32(const void* p)")
    dev = _sub(dev, "u16* __restrict__ out, int G, int NIT, int K, int KS, int out_stride, int act_shift) {\n    extern __shared__ __align__(16) u8 smem_raw[];\n    __shared__ int s_flag;\n    u32* s_lut",
               "u16* __restrict__ out, int G, int NIT, int K, int KS, int out_stride, int act_shift, int pref_mode) {\n    extern __shared__ __align__(16) u8 smem_raw[];\n    __shared__ int s_flag;\n    u32* s_lut")
    dev = _sub(dev, "        prefetch_batch(w0, s0, wp, sp);\n\n        __syncthreads();  // previous z iteration is done with s_act / s_flag\n",
               "        prefetch_batch(w0, s0, wp, sp);\n"
               "        if (!FUSE && pref_mode > 0) {   // C33: GEMM2's weights do not depend on GEMM1: blocks 1.. of this warp's 4 KB-block stream (block 0 = the two register batches) to L2 before the wait\n"
               "            const int nblk = (nit * 512) >> 12;\n"
               "            int last = pref_mode == 1 ? (16 / NW > 0 ? 16 / NW : 1) + 1 : nblk;\n"
               "            if (last > nblk) last = nblk;\n"
               "            const char* pb = reinterpret_cast<const char*>(wp - lane) + (size_t)lane * 128;\n"
               "            for (int i = 1; i < last; ++i) l2_prefetch(pb + (size_t)i * 4096);\n        }\n\n        __syncthreads();  // previous z iteration is done with s_act / s_flag\n")
    host = _sub(host, "static const int SM_SMEM_MAX = 98304;\n", "static const int SM_SMEM_MAX = 98304;\nstatic int g_pref_mode = 0;\n")
    host = _sub(host, "i_os = (int)out_stride, i_as = (int)act_shift;\n    void* args[] = {&a_wq, &a_sq, &a_gs, &a_lut, &a_act, &a_tab, &a_part, &a_cnt, &a_out, &i_G, &i_NIT, &i_K, &i_KS, &i_os, &i_as};",
                "i_os = (int)out_stride, i_as = (int)act_shift, i_pf = g_pref_mode;\n    void* args[] = {&a_wq, &a_sq, &a_gs, &a_lut, &a_act, &a_tab, &a_part, &a_cnt, &a_out, &i_G, &i_NIT, &i_K, &i_KS, &i_os, &i_as, &i_pf};")
    host = _sub(host, "void smallm_init() {\n", "void smallm_set_pref(int64_t mode) { g_pref_mode = (int)mode; }\n\nvoid smallm_init() {\n")
    cpp = _sub(cpp, "void smallm_init();\n", "void smallm_set_pref(int64_t mode);\nvoid smallm_init();\n")
    return dev, host, cpp


def build():
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_decode_layer"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    mid = ("\n\n# ---- twins of the Triton kernels of kernels/muse_decode_layer/sonnet_v5f.py with an L2 prefetch before gdc_wait (generated by exact-match substitutions of its source text)\n" + twins() + "\n")
    dev, host, cpp = smallm_twin()
    for t in (dev, host):
        assert "'''" not in t
    sm = ("\n\n# ---- the small-M CUDA source of sonnet_v5f with the GEMM2 L2 prefetch before pdl_wait (second extension, built in the study); generated\n"
          f"_MC_SM_DEVICE_SRC = r'''{dev}'''\n_MC_SM_HOST_SRC = r'''{host}'''\n_MC_SM_CPP_SRC = {cpp!r}\n")
    mid += sm
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_decode_layer", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_decode_layer/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + mid + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
