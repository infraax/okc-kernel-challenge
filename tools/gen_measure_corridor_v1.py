"""Regenerate kernels/muse_decode_layer/measure_corridor_v1.py (C33, MEASUREMENT-ONLY) =
    line 1 of sonnet_v5f.py + the MEASUREMENT-ONLY header + sonnet_v5f.py verbatim (kernel_fn / prepare unchanged: the board kernel)
  + twins of the Triton kernels we launch (_gemv_splitk, _router_fix_kernel, _unpool_kernel, _pre_norm_kernel, _epilogue_kernel; names prefixed _mc_) produced from
    sonnet_v5f's own source text by exact-match substitutions (fail loudly when the board source changes): L2 prefetch of the CTA's first weight bytes BEFORE gdc_wait
  + the small-M CUDA source with the same prefetch before its pdl_wait (compiled as a second extension in the study)
  + generate_input of problems/muse_decode_layer/reference.py inlined by tools/make_trace.py's ast inliner (names prefixed _tr_)
  + tools/measure_corridor_v1_part.py (the study, wraps prepare()).
Run after any change to an input:   .venv/bin/python tools/gen_measure_corridor_v1.py"""
