#!/usr/bin/env python3
"""Regenerate kernels/muse_bf16_proj/measure_gemv_ws_v1.py (C39, MEASUREMENT-ONLY) =
    line 1 of director_v2.py + the MEASUREMENT-ONLY header + director_v2.py verbatim (kernel_fn / prepare unchanged: the board kernel, 1.170x)
  + generate_input of problems/muse_bf16_proj/reference.py inlined by tools/make_trace.py's ast inliner (names prefixed _tr_)
  + tools/measure_gemv_ws_v1_part.py (the study, wraps prepare()).
Run after any change to an input:   .venv/bin/python tools/gen_measure_gemv_ws_v1.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_bf16_proj" / "director_v2.py"
PART = ROOT / "tools" / "measure_gemv_ws_v1_part.py"
OUT = ROOT / "kernels" / "muse_bf16_proj" / "measure_gemv_ws_v1.py"

MARKER = '''# MEASUREMENT-ONLY (C39 v1, WSTREAM-style skinny BF16 GEMV): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_gemv_ws_v1.py: do not edit.
# kernel_fn / prepare below are kernels/muse_bf16_proj/director_v2.py VERBATIM (the board kernel, 1.170x). prepare() runs v2's prepare(), then (untimed, <= 262 s; cells that do not
# fit are dropped, not run late) builds one CUDA extension (torch load_inline, `-w`, 10 instantiations of a tensor-core GEMV: weights = the mma B operand, one 16-byte
# ld.global.nc.L1::no_allocate per lane and k32 window, U = 8 / 16 loads in flight per lane, x staged in smem or read through L1, split-K with a last-CTA fixup in fixed slice order)
# and times on generate_input-recipe inputs (3 seeds), for qkv_gate, o, pooler, unpooler (n = 1024 at m <= 8) and router (hi + lo BF16 weights, FP32 out) at m = 1, 8, 16, 32:
# torch.matmul (cuBLAS), the board kernel (the _PLAN cell) and up to 36 legal WS variants per cell, each as a CUDA-graph replay after a read-only 128 MB L2 flush, the fixed replay
# overhead subtracted, median of 5 per seed, interleaved rounds with the board kernel as pivot; every output checked against an FP64 reference with the problem's bounds
# (1e-2, router 1e-4, probe rows 1e-3). Output (<= 14 KB): `S` lines first (per layer and m: cu / board / best WS, TB/s on unique bytes, error, OK), a `D` line (cells where WS beats
# the board by >= 5 %), then `B gemv <layer> m=<m> | <variant> us=<..> x=<board/variant>`.
'''


def build():
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_bf16_proj"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_bf16_proj", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_bf16_proj/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
