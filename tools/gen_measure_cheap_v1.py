#!/usr/bin/env python3
"""Regenerate kernels/muse_bf16_proj/measure_cheap_v1.py (C23, MEASUREMENT-ONLY) =
    line 1 of director_v1b.py + the MEASUREMENT-ONLY header + director_v1b.py verbatim (kernel_fn / prepare unchanged: the board kernel)
  + the fixup kernel, its host helpers and the candidate table of director_v2.py (names prefixed _mc_; one source of truth: what is measured is what ships)
  + generate_input of problems/muse_bf16_proj/reference.py inlined by tools/make_trace.py's ast inliner (names prefixed _tr_)
  + tools/measure_cheap_v1_part.py (the study, wraps prepare()).
Run after any change to an input:   .venv/bin/python tools/gen_measure_cheap_v1.py"""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_bf16_proj" / "director_v1b.py"
V2 = ROOT / "kernels" / "muse_bf16_proj" / "director_v2.py"
PART = ROOT / "tools" / "measure_cheap_v1_part.py"
OUT = ROOT / "kernels" / "muse_bf16_proj" / "measure_cheap_v1.py"

MARKER = '''# MEASUREMENT-ONLY (C23 v1, design/fable-09-out.md D4 section 4): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_cheap_v1.py: do not edit.
# kernel_fn / prepare below are kernels/muse_bf16_proj/director_v1b.py VERBATIM (the board kernel, 1.156x). prepare() runs v1b's prepare(), then (untimed, <= 262 s; variants that
# do not fit are dropped, not run late) times on generate_input-recipe inputs (3 seeds, the 30 judged shapes), each variant as a CUDA-graph replay after a read-only L2 flush,
# median of 5 per seed, interleaved rounds with the board kernel as pivot, every output checked against an FP64 reference with the problem's bounds (router 1e-4, probe rows 1e-3):
#   unpooler m 1 / 8 (n = 1024)  direct GEMV (SPLIT = 1, no zero-fill, no atomics) _CFG (32,256,1,4,4) and neighbours; last-CTA fixup split-K
#   router m <= 32               last-CTA fixup (no torch.zeros, no atomics; >= 256 CTAs) with 3 configs (+ the plain reduction loop RG 1)
#   router m 128 / 256           one M block (BM = m: W read once) and BM = 64 with K-split fixup; against two cuBLAS GEMMs on hi / lo
#   every shape                  cuBLAS: torch.mm and SGLang's own dispatch (the baseline), as a reference
# Output (<= 14 KB): `S` summary lines first (incl. the estimated problem speedup against the in-run baseline), then `B bf16 <layer> m=<m> | <variant> us=<..> x=<board/variant>`.
'''

KERNEL_NAMES = ("_gemv_fix", "_fix_fits", "_run_fix")


def _segment(tree, text, name, kind):
    for node in tree.body:
        if kind == "def" and isinstance(node, ast.FunctionDef) and node.name == name:
            start = node.decorator_list[0].lineno if node.decorator_list else node.lineno
            return "\n".join(text.splitlines()[start - 1:node.end_lineno])
        if kind == "assign" and isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.get_source_segment(text, node)
    raise KeyError(name)


def v2_pieces():
    text = V2.read_text()
    tree = ast.parse(text)
    parts = [_segment(tree, text, n, "def") for n in KERNEL_NAMES]
    block = "\n\n\n".join(parts)
    for n in KERNEL_NAMES:
        block = re.sub(rf"\b{n}\b", "_mc" + n, block)
    consts = "\n".join(_segment(tree, text, n, "assign") for n in ("_CANDIDATES", "FIX_WS_FLOATS", "FIX_TILES"))
    consts = consts.replace("_CANDIDATES", "_MC_CANDIDATES", 1)
    return block, consts


def build():
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_bf16_proj"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    block, consts = v2_pieces()
    mid = ("\n\n# ---- the fixup kernel, its host helpers and the candidate table of kernels/muse_bf16_proj/director_v2.py (what is measured is what ships); generated\n"
           + consts + "\n\n\n" + block + "\n")
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_bf16_proj", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_bf16_proj/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + mid + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
