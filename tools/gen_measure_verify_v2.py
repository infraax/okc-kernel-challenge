#!/usr/bin/env python3
"""Regenerate kernels/muse_attention_decode/measure_verify_v2.py (C27 optional, MEASUREMENT-ONLY) =
    line 1 of sonnet_v5.py + the MEASUREMENT-ONLY header + sonnet_v5.py verbatim (kernel_fn unchanged: the C27 board candidate)
  + the judged shape table (same as v1) + generate_input of problems/muse_attention_decode/reference.py inlined by tools/make_trace.py's ast inliner
  + tools/measure_verify_v2_part.py (config sweeps of the BOARD kernels _full_kernel / _full_cat_kernel, run at import).
No kernel twins: every variant is a launch config (BN, stages, warps, programs) of kernels already in sonnet_v5.
Run after any change to an input:   .venv/bin/python tools/gen_measure_verify_v2.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_attention_decode" / "sonnet_v5.py"
PART = ROOT / "tools" / "measure_verify_v2_part.py"
OUT = ROOT / "kernels" / "muse_attention_decode" / "measure_verify_v2.py"

MARKER = '''# MEASUREMENT-ONLY (C27 sweep v2, after the C26' result design/breakdown/c26-attention-verify-result.md): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_verify_v2.py: do not edit.
# kernel_fn below is kernels/muse_attention_decode/sonnet_v5.py VERBATIM (sonnet_v3 + BN128 for verify-full at batch >= 16). At IMPORT (no prepare()) the study runs (<= 240 s) on the judged
# FULL-layer shapes #9 / #11 / #7 (verify batch 16 / 32 / 1) and #3 / #5 (decode 16 / 32); 3 seeds, CUDA-graph replays after a read-only L2 flush, interleaved rounds, median of 5 per seed.
# Variants are launch configs of the board kernels (nothing is copied): verify `_full_kernel` BN 64 / 128 / 256 x stages 2-4 x warps 4 / 8 x programs 192-512;
# decode `_full_cat_kernel` BN 64 / 128 / 256 x stages 2-4 x warps 2 / 4 x programs 528 / 792 / 1056. x = reference variant (verify B128S3W4, decode C64S3W2 = the board) / variant.
# Output (<= 14 KB): `S` summary lines first, `C` PTX counts per variant, then `B attn #<shape> seed=<s> | <variant> us=<..> x=<ref/variant> err=<L2>/<FP32 partials>`.
'''


def build():
    from gen_measure_verify_v1 import CASES
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_attention_decode"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    consts = ("\n\n# ---- generated constants\n_MV_CASES = [\n" + "".join(f"    ({i}, {lab!r}, {c!r}),\n" for i, lab, c in CASES) + "]\n")
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_attention_decode", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_attention_decode/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + consts + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
