"""Regenerate kernels/muse_attention_decode/measure_verify_v1.py (C26', MEASUREMENT-ONLY) =
    line 1 of sonnet_v3.py + the MEASUREMENT-ONLY header + sonnet_v3.py verbatim (kernel_fn unchanged: the board kernel)
  + twins of `_full_kernel` / `_step` / `_softmax_step` (names prefixed _mv_, produced from sonnet_v3's own source text by exact-match substitutions that
    fail loudly when the board source changes: one source of truth, nothing is retyped)
  + generate_input of problems/muse_attention_decode/reference.py inlined by tools/make_trace.py's ast inliner (names prefixed _tr_)
  + tools/measure_verify_v1_part.py (variant constants / helpers / launcher / the study, run at import).
Run after any change to an input:   .venv/bin/python tools/gen_measure_verify_v1.py"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRC = ROOT / "kernels" / "muse_attention_decode" / "sonnet_v3.py"
PART = ROOT / "tools" / "measure_verify_v1_part.py"
OUT = ROOT / "kernels" / "muse_attention_decode" / "measure_verify_v1.py"

# exp2 on [-0.5, 0.5] relative-error fit, degree 6 (highest power first); FP32 Horner max rel error 1.0e-7 (ex2.approx.f32: 2.4e-7)
EXP2_COEFS = (0.0001534581242594868, 0.0013399932067841291, 0.009618489071726799, 0.05550328642129898, 0.24022646248340607,
              0.6931471824645996, 1.0)

# judged shapes (problems/muse_attention_decode/TASK.md; index = row of the table, 0-based) with the study's labels; seeds are the study's own
CASES = [
    (9, "verify16", dict(batch=16, ctx=80000, dist="coherent", heads="tp8", layer="full", page=1, q_len=8, spread="agentic")),
    (11, "verify32", dict(batch=32, ctx=80000, dist="coherent", heads="tp8", layer="full", page=1, q_len=8, spread="agentic")),
    (7, "verify1", dict(batch=1, ctx=80000, dist="coherent", heads="tp8", layer="full", page=1, q_len=8)),
    (3, "decode16", dict(batch=16, ctx=80000, dist="coherent", heads="tp8", layer="full", page=1, spread="agentic")),
    (5, "decode32", dict(batch=32, ctx=80000, dist="coherent", heads="tp8", layer="full", page=1, spread="agentic")),
]

MARKER = '''# MEASUREMENT-ONLY (C26' v1, design/fable-09-out.md D4 section 3 + research/2026-10-26 idea 2): NEVER submit; `okc check` it. GENERATED by tools/gen_measure_verify_v1.py: do not edit.
# kernel_fn below is kernels/muse_attention_decode/sonnet_v3.py VERBATIM (the board kernel, 1.689x). At IMPORT (this problem has no prepare()) the study runs (<= 240 s, variants that do not
# fit are dropped, not run late) on the judged FULL-layer shapes #9 / #11 / #7 (verify batch 16 / 32 / 1, q_len 8) and #3 / #5 (decode 16 / 32, reference), inputs from the generate_input recipe
# (3 seeds), CUDA-graph replays after a read-only L2 flush, interleaved rounds, median of 5 per seed. Variants are COPIES of `_full_kernel` with constexpr switches (the board code is never touched):
#   base        the copy with every switch off (must equal the board kernel: outputs bit-identical, same PTX counts)
#   GATHER      K / V tiles loaded (int32 words, evict_first), all compute replaced by an XOR fold into a sink stored by lane 0
#   MMAONLY     loads + the two tensor-core dots (logits in FP16 as P, V as raw FP8 pairs viewed FP16): no exp2, no max/sum, no FP8->FP16 convert; keeps the cp.async pipeline
#   NOEXP       exp2 replaced by a linear op (1 FFMA), result still feeds P.V          NOCVT   V used as raw FP8 bits (FP16 view [BN, 32]: P.V has N = 32), no convert / smem round trip
#   EXPSPLIT25 / 50   25 % / 50 % of the exp2 evaluations on FMA units (degree-6 FP32 polynomial, rel error 1e-7), the rest MUFU ex2; error vs base reported
#   RED         the reducer only                                                          PROGx2 PROGd2 ST3 ST2 BN128 W8   programs x2 / /2, stages 3 / 2, BN 128 (stages 3), 8 warps
# Output (<= 14 KB): `S` summary lines first, `C` PTX counts per variant, then `B attn #<shape> seed=<s> | <variant> us=<..> x=<base/variant> err=<..>`.
'''


def _segment(tree, text, name):
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            start = node.decorator_list[0].lineno if node.decorator_list else node.lineno
            return "\n".join(text.splitlines()[start - 1:node.end_lineno])
    raise KeyError(name)


def _sub(text, old, new, count=1):
    n = text.count(old)
    if n != count:
        raise SystemExit(f"gen_measure_verify_v1: expected {count} x {old[:70]!r} in the board source, found {n}: sonnet_v3.py changed, update the substitutions")
    return text.replace(old, new)


def _indent(block, n):
    return "\n".join((" " * n + line if line.strip() else line) for line in block.split("\n"))


def poly_src():
    c = EXP2_COEFS
    lines = ["@triton.jit", "def _mv_exp2_poly(x):",
             '    """2^x for x <= 0 on the FMA units: clamp at -126, round x to n with the 1.5 * 2^23 trick, degree-6 polynomial of f = x - n,',
             '    2^n added into the exponent field (the low 9 bits of the rounded sum are n). No MUFU, no F2I."""',
             "    x = tl.maximum(x, -126.0)", "    t = x + 12582912.0", "    f = x - (t - 12582912.0)", f"    p = f * {c[0]!r} + {c[1]!r}"]
    lines += [f"    p = p * f + {v!r}" for v in c[2:]]
    lines += ["    bits = p.to(tl.int32, bitcast=True) + (t.to(tl.int32, bitcast=True) << 23)", "    return bits.to(tl.float32, bitcast=True)"]
    return "\n".join(lines)


def twins():
    text = SRC.read_text()
    tree = ast.parse(text)
    # ---- _softmax_step
    s = _segment(tree, text, "_softmax_step")
    s = _sub(s, "def _softmax_step(sc, c, m_i, l_i, acc, vc, CDTYPE: tl.constexpr):", "def _mv_softmax_step(sc, c, m_i, l_i, acc, vc, CDTYPE: tl.constexpr, VAR: tl.constexpr):")
    s = _sub(s, "    p = tl.exp2(sc * c - (m_use * c)[:, None])", "    p = _mv_p(sc * c - (m_use * c)[:, None], VAR)")
    # ---- _step
    st = _segment(tree, text, "_step")
    st = _sub(st, "def _step(q, ku, vu, m_i, l_i, acc, c, tm, need_mask, NATIVE_LOAD: tl.constexpr, QK8: tl.constexpr, CDTYPE: tl.constexpr):",
              "def _mv_step(q, ku, vu, m_i, l_i, acc, c, tm, need_mask, NATIVE_LOAD: tl.constexpr, QK8: tl.constexpr, CDTYPE: tl.constexpr, VAR: tl.constexpr):")
    st = _sub(st, "    if NATIVE_LOAD:\n        vc = vu.to(tl.float8e4nv, bitcast=True).to(CDTYPE)\n",
              "    if VAR == V_NOCVT or VAR == V_MMAONLY:\n        vc = vu                      # raw FP8 bit pairs, already an FP16 tile\n"
              "    elif NATIVE_LOAD:\n        vc = vu.to(tl.float8e4nv, bitcast=True).to(CDTYPE)\n")
    st = _sub(st, "    return _softmax_step(sc, c, m_i, l_i, acc, vc, CDTYPE)",
              "    if VAR == V_MMAONLY:\n        m_o = m_i\n        l_o = l_i\n        a_o = tl.dot(sc.to(CDTYPE), vc, acc)\n"
              "    else:\n        m_o, l_o, a_o = _mv_softmax_step(sc, c, m_i, l_i, acc, vc, CDTYPE, VAR)\n    return m_o, l_o, a_o")
    # ---- _full_kernel
    k = _segment(tree, text, "_full_kernel")
    k = _sub(k, "def _full_kernel(", "def _mv_full_kernel(")
    k = _sub(k, "    part_o, part_m, part_l,\n    sm_scale", "    part_o, part_m, part_l, sink_ptr,\n    sm_scale")
    k = _sub(k, "BN: tl.constexpr, BT: tl.constexpr,\n):", "BN: tl.constexpr, BT: tl.constexpr, VAR: tl.constexpr, ACOLS: tl.constexpr,\n):")
    k = _sub(k, "    a0 = tl.zeros([M, 64], tl.float32)", "    a0 = tl.zeros([M, ACOLS], tl.float32)")
    k = _sub(k, "    a1 = tl.zeros([M, 64], tl.float32)", "    a1 = tl.zeros([M, ACOLS], tl.float32)")
    k = _sub(k, "        hb = h0 * 64\n        for i in range(nt):", "        hb = h0 * 64\n        sk = tl.zeros([BN, 16], tl.int32)\n        for i in range(nt):")
    k = _sub(k, "_gather(k_cache, v_cache, pgA, tc, end, hb, d, PAGE, HKV)", "_mv_gather(k_cache, v_cache, pgA, tc, end, hb, d, PAGE, HKV, VAR)")
    old_tail = (
        "            m0, l0, a0 = _step(q0, kA0, vA0, m0, l0, a0, c, tm, need_mask, NATIVE_LOAD, QK8, CDTYPE)\n"
        "            m1, l1, a1 = _step(q1, kA1, vA1, m1, l1, a1, c, tm, need_mask, NATIVE_LOAD, QK8, CDTYPE)\n"
        "    else:\n"
        "        vs = tl.load(v_scale_ptr)\n"
        "        m0, l0, a0 = _own_head(qkv, positions, cache_loc, k_cache, v_cache, b, h0, q0, j, c, ks, vs, log2_theta, m0, l0, a0,\n"
        "                               L, HQ, HKV, ROPE, NATIVE_STORE, QK8, CDTYPE, BT)\n"
        "        m1, l1, a1 = _own_head(qkv, positions, cache_loc, k_cache, v_cache, b, h0 + 1, q1, j, c, ks, vs, log2_theta, m1, l1, a1,\n"
        "                               L, HQ, HKV, ROPE, NATIVE_STORE, QK8, CDTYPE, BT)\n")
    own = old_tail.split("    else:\n", 1)[1]
    new_tail = (
        "            if VAR == V_GATHER:\n"
        "                sk = sk ^ kA0 ^ kA1 ^ vA0 ^ vA1      # the fold: every loaded word is consumed (cannot be deleted)\n"
        "            else:\n"
        "                m0, l0, a0 = _mv_step(q0, kA0, vA0, m0, l0, a0, c, tm, need_mask, NATIVE_LOAD, QK8, CDTYPE, VAR)\n"
        "                m1, l1, a1 = _mv_step(q1, kA1, vA1, m1, l1, a1, c, tm, need_mask, NATIVE_LOAD, QK8, CDTYPE, VAR)\n"
        "        if VAR == V_GATHER:\n"
        "            tl.store(sink_ptr + (b * HKV + h0) * (NSPLIT + 1) + s, tl.sum(tl.sum(sk, 1), 0))   # scalar: one lane stores\n"
        "    else:\n"
        "        if ACOLS == 64:\n" + _indent(own.rstrip("\n"), 4) + "\n")
    k = _sub(k, old_tail, new_tail)
    k = _sub(k, "        tl.store(part_o + pidx[:, None] * 64 + d, a0, mask=rvalid[:, None])",
             "        tl.store(part_o + pidx[:, None] * 64 + tl.arange(0, ACOLS)[None, :], a0, mask=rvalid[:, None])")
    k = _sub(k, "        tl.store(part_o + pidx[:, None] * 64 + d, a1, mask=rvalid[:, None])",
             "        tl.store(part_o + pidx[:, None] * 64 + tl.arange(0, ACOLS)[None, :], a1, mask=rvalid[:, None])")
    return "\n\n\n".join([poly_src(), s, st, k])


def build():
    from make_trace import inline_generator

    src = SRC.read_text().splitlines(keepends=True)
    assert src[0].strip() == "# okc: problem=muse_attention_decode"
    body = src[0] + MARKER + "".join(src[1:])
    if not body.endswith("\n"):
        body += "\n"
    mid = ("\n\n# ---- twins of _softmax_step / _step / _full_kernel of kernels/muse_attention_decode/sonnet_v3.py (generated by exact-match substitutions of its source text)\n"
           + twins() + "\n")
    consts = ("\n\n# ---- generated constants\n_MV_EXP2_C = " + repr(EXP2_COEFS) + "\n_MV_CASES = [\n"
              + "".join(f"    ({i}, {lab!r}, {c!r}),\n" for i, lab, c in CASES) + "]\n")
    gen_src, gen_name, params = inline_generator(ROOT / "problems" / "muse_attention_decode", reserved=())
    assert gen_name == "_tr_generate_input", gen_name
    gen = "\n\n# ---- generate_input of problems/muse_attention_decode/reference.py, inlined by tools/make_trace.py's ast inliner\n" + gen_src
    return body + mid + consts + gen + "\n\n" + PART.read_text()


if __name__ == "__main__":
    text = build()
    compile(text, str(OUT), "exec")
    OUT.write_text(text)
    print("wrote", OUT, len(text), "bytes")
